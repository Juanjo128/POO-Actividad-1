public class suma {
   
    public static double calculo1(double SUMA, double x) {
    return SUMA + x;
    }

    public static double calculo2( double x, double y) {
    return x + Math.pow(y,2);
    }   

    public static double calculo3(double SUMA, double x, double y) {
    return SUMA + (x/y);
}

}
